function numbertype(num)
{
    if(num >0) 
    {
        console.log(num , "The number is greater than");
        
    }
    else if(num < 0) 
    {
        console.log(num , "The number is lesser than");
        
    }
    else
    {
        console.log(num , "The number is Zero");
        
    }
}

numbertype(22);
numbertype(-5)
numbertype(0)
numbertype(1)
numbertype(-6)
